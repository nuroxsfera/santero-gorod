/**
 * Curated Novosibirsk POI catalog (H3).
 * Public landmarks with approximate OSM-aligned coordinates.
 * Not a full city extract — labeled as curated catalog, not live OSM dump.
 */
function p(
  partial: Omit<Place, "localityId" | "regionId" | "organizationId" | "status"> & {
    organizationId?: string | null;
  }
): Place {
  return {
    ...partial,
    localityId: PILOT_CITY.localityId,
    regionId: PILOT_CITY.regionId,
    organizationId: partial.organizationId ?? null,
    status: "active",
  };
}

